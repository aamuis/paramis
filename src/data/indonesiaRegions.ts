export function getAllProvinces(): string[] {
  return INDONESIA_PROVINCES.map(p => p.name);
}

export function getCitiesByProvince(provinceName: string): string[] {
  const match = INDONESIA_PROVINCES.find(p => p.name.toLowerCase() === provinceName.toLowerCase());
  return match ? match.cities : [];
}

export function findProvinceByCity(cityName: string): string | null {
  const lowerCity = cityName.toLowerCase();
  for (const prov of INDONESIA_PROVINCES) {
    if (prov.cities.some(c => c.toLowerCase().includes(lowerCity) || lowerCity.includes(c.toLowerCase()))) {
      return prov.name;
    }
  }
  return null;
}
